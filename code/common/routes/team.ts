import { ICommon_Model_Team } from '../model/team';
import { ICommon_Model_Team_Role } from '../model/team_role';
import { Permission_Types } from '../permission/permission';
import { ECommon_Services } from '../types';
import { ICommon_Route_Res_Team_List } from './response';
import { ECommon_HttpApi_Method } from "./types";
const api={
    baseUrl:"/team",
    service:ECommon_Services.User,
    routes:{
        create:{//创建团队
            method:ECommon_HttpApi_Method.POST,
            path:"/item",
            req:<{
                name:string                
            }>{},
            res:<ICommon_Model_Team>{}
        },
        info:{//团队信息
            method:ECommon_HttpApi_Method.GET,
            path:"/item",
            req:<{
                teamId:string                
            }>{},
            res:<ICommon_Model_Team>{}
        },
        update:{//更新团队信息
            method:ECommon_HttpApi_Method.PUT,
            path:"/item",
            req:<{
                teamId:string,
                name:string                
            }>{},
            res:<ICommon_Model_Team>{},
            permission:[Permission_Types.Team.EDIT]
        },
        remove:{//删除团队
            method:ECommon_HttpApi_Method.DELETE,
            path:"/item",
            req:<{
                teamId:string                
            }>{},
            res:{},
            permission:{
                data:[Permission_Types.Team.DELETE],
                delete:true
            }
        },
        members:{//团队成员列表
            method:ECommon_HttpApi_Method.GET,
            path:"/members",
            req:<{
                teamId:string             
            }>{},
            res:<{
                id:string,
                name:string,
                photo:string,
                role:Omit<ICommon_Model_Team_Role,"team_id">
            }[]>{},
            permission:[Permission_Types.Team.READ]
        },
        addMember:{//添加团队成员
            method:ECommon_HttpApi_Method.POST,
            path:"/add_member",
            req:<{
                teamId:string,
                userId:string,
                roleId:string                
            }>{},
            res:{},
            permission:{
                data:[Permission_Types.Team.EDIT],
                delete:true
            }
        },
        removeMember:{//删除团队成员
            method:ECommon_HttpApi_Method.DELETE,
            path:"/remove_member",
            req:<{
                teamId:string,
                userId:string                
            }>{},
            res:{},
            permission:{
                data:[Permission_Types.Team.EDIT],
                delete:true
            }
        },
        changeRole:{//修改团队成员权限
            method:ECommon_HttpApi_Method.PUT,
            path:"/role",
            req:<{
                teamId:string,
                userId:string,
                roleId:string             
            }>{},
            res:{},
            permission:{
                data:[Permission_Types.Team.EDIT],
                delete:true
            }
        },
        roles:{//团队权限列表
            method:ECommon_HttpApi_Method.GET,
            path:"/roles",
            req:<{
                teamId:string           
            }>{},
            res:<ICommon_Model_Team_Role[]>{},
            permission:[Permission_Types.Team.READ]
        },
        list:{
            method:ECommon_HttpApi_Method.GET,
            path:"/list",
            req:<{
                keyword?:string,
                page:number,
                size:number             
            }>{},
            res:<ICommon_Route_Res_Team_List>{},
        },
        filterTeam:{
            method:ECommon_HttpApi_Method.GET,
            path:"/filter",
            req:<{
                name:string      
            }>{},
            res:<{
                name:string,
                id:string,
                photo:string
            }[]>{},
        }
    }
}
export=api